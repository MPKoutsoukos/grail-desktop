// Writes src/licences.ts: the copyright notice of every library and font grail desktop ships, and the full text of
// each licence they use (MIT, ISC, SIL OFL 1.1), read from their own LICENSE files in node_modules. Packages offered
// under "MIT OR Apache-2.0" (Tauri) are used under MIT. MIT, ISC and the OFL require the notice and the licence
// text to travel with the app, so the Licences screen shows them in full.
// Run after adding or removing a dependency: node scripts/licences.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

const licenceFile = (dir) => readdirSync(dir).find((f) => /^licen[cs]e(\.md|\.txt)?$/i.test(f))
const copyrightOf = (text) => (text.match(/^.*copyright.*$/im) || [''])[0].trim()
const pick = (licence) => (/\bMIT\b/.test(licence) ? 'MIT' : /\bISC\b/.test(licence) ? 'ISC' : /OFL-1\.1/.test(licence) ? 'OFL-1.1' : licence)

const notices = []
const texts = {}
for (const name of Object.keys(pkg.dependencies).sort()) {
  const dir = join(root, 'node_modules', ...name.split('/'))
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const file = licenceFile(dir)
  const text = file ? readFileSync(join(dir, file), 'utf8') : ''
  const licence = pick(String(meta.license || ''))
  const label = name.startsWith('@fontsource-variable/') ? `${name.split('/')[1]} (font)` : name
  notices.push({ name: label, licence, copyright: copyrightOf(text) })
  if (licence === 'MIT' && !texts.MIT && /permission is hereby granted/i.test(text)) texts.MIT = text.slice(text.search(/permission is hereby granted/i)).trim()
  if (licence === 'ISC' && !texts.ISC && /permission to use/i.test(text)) texts.ISC = text.slice(text.search(/permission to use/i)).trim()
  if (licence === 'OFL-1.1' && !texts['OFL-1.1'] && /SIL OPEN FONT LICENSE/i.test(text)) texts['OFL-1.1'] = text.slice(text.search(/this font software is licensed|SIL OPEN FONT LICENSE/i)).trim()
}
// The native shell: Tauri's runtime, built in from Rust crates rather than npm.
notices.push({ name: 'Tauri (runtime)', licence: 'MIT', copyright: 'Copyright (c) 2017 - Present Tauri Programme within The Commons Conservancy' })

const out = `// Generated by scripts/licences.mjs from the LICENSE files in node_modules: don't edit by hand.
export type Notice = { name: string; licence: string; copyright: string }
export const NOTICES: Notice[] = ${JSON.stringify(notices, null, 2)}
export const LICENCE_TEXTS: Record<string, string> = ${JSON.stringify(texts, null, 2)}
`
writeFileSync(join(root, 'src', 'licences.ts'), out)
console.log(`${notices.length} notices; licence texts: ${Object.keys(texts).join(', ')}`)
